#!/usr/bin/env node
// Build css/tokens.css and src/generated/tokens.ts from tokens/tokens.json and enforce the contrast contract.
// Usage: node scripts/build-tokens.mjs            writes both files, fails on a contrast breach
//        node scripts/build-tokens.mjs --check    verifies the contract only
//        node scripts/build-tokens.mjs --print    prints the CSS it would write (used by the tests)
//        node scripts/build-tokens.mjs --print-ts prints the TypeScript it would write
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const tokens = JSON.parse(readFileSync(join(root, 'tokens/tokens.json'), 'utf8'));
const mode = process.argv[2];

const kebab = (s) => s.replace(/[A-Z]/g, (c) => '-' + c.toLowerCase());
const entries = (group) => Object.entries(group).filter(([k]) => !k.startsWith('$'));

const palette = Object.fromEntries(entries(tokens.color).map(([k, v]) => [k, v.$value]));
const resolve = (ref) => {
  if (!(ref in palette)) throw new Error(`Unknown colour "${ref}"`);
  return palette[ref];
};

function luminance(hex) {
  const n = parseInt(hex.slice(1), 16);
  const ch = [n >> 16, (n >> 8) & 255, n & 255].map((c) => {
    const s = c / 255;
    return s <= 0.04045 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  });
  return 0.2126 * ch[0] + 0.7152 * ch[1] + 0.0722 * ch[2];
}
const contrast = (a, b) => {
  const [hi, lo] = [luminance(a), luminance(b)].sort((x, y) => y - x);
  return (hi + 0.05) / (lo + 0.05);
};

const failures = [];
const report = [];
for (const [brand, roles] of entries(tokens.theme)) {
  for (const [scheme, i] of [['light', 0], ['dark', 1]]) {
    for (const [fg, bg, min] of tokens.contract.pairs) {
      const ratio = contrast(resolve(roles[fg][i]), resolve(roles[bg][i]));
      const line = `${brand.padEnd(8)} ${scheme.padEnd(5)} ${fg} on ${bg}`.padEnd(40) + ` ${ratio.toFixed(2)} (min ${min})`;
      report.push(line);
      if (ratio < min) failures.push(line);
    }
  }
}

// Each group becomes --<group>-<name>, in this order.
const GROUPS = ['color', 'font', 'size', 'space', 'radius', 'stroke', 'shadow', 'grid', 'texture', 'rotate', 'motion'];
const css = [
  '/* Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand. */',
  ':root {',
  '  color-scheme: light dark;',
  ...GROUPS.flatMap((group) => entries(tokens[group]).map(([k, v]) => `  --${group}-${kebab(k)}: ${v.$value};`)),
  '}',
  ':root[data-theme="light"] { color-scheme: light; }',
  ':root[data-theme="dark"] { color-scheme: dark; }',
];
for (const [brand, roles] of entries(tokens.theme)) {
  css.push(`${brand === 'club' ? ':root, ' : ''}[data-brand="${brand}"] {`);
  for (const [role, [light, dark]] of Object.entries(roles)) {
    css.push(`  --${kebab(role)}: light-dark(var(--color-${kebab(light)}), var(--color-${kebab(dark)}));`);
  }
  for (const [k, v] of Object.entries(tokens.style[brand])) css.push(`  --${kebab(k)}: ${v};`);
  css.push('}');
}
css.push('');

const values = (group) => Object.fromEntries(entries(group).map(([k, v]) => [k, v.$value]));
const themes = Object.fromEntries(entries(tokens.theme).map(([brand, roles]) => [
  brand, Object.fromEntries(Object.entries(roles).map(([role, pair]) => [role, pair.map(resolve)])),
]));
const roles = Object.keys(entries(tokens.theme)[0][1]);
const ts = [
  '// Generated by scripts/build-tokens.mjs from tokens/tokens.json. Do not edit by hand.',
  '',
  `export const colors = ${JSON.stringify(values(tokens.color), null, 2)} as const;`,
  'export type ColorName = keyof typeof colors;',
  '',
  `export const fonts = ${JSON.stringify(values(tokens.font), null, 2)} as const;`,
  '',
  '/** Each role resolved to hex for both brands, as [light, dark]. */',
  `export const themes = ${JSON.stringify(themes, null, 2)} as const;`,
  'export type ThemeRole = keyof typeof themes.club;',
  '',
  '/** The CSS custom property each role is published as, e.g. var(--on-accent). */',
  `export const themeVariables = ${JSON.stringify(Object.fromEntries(roles.map((r) => [r, `--${kebab(r)}`])), null, 2)} as const satisfies Record<ThemeRole, \`--\${string}\`>;`,
  '',
].join('\n');

if (mode === '--print' || mode === '--print-ts') {
  process.stdout.write(mode === '--print' ? css.join('\n') : ts);
  process.exit(failures.length ? 1 : 0);
}
console.log(report.join('\n'));
if (failures.length) {
  console.error(`\n${failures.length} contrast pair(s) below contract:\n${failures.join('\n')}`);
  process.exit(1);
}
if (mode !== '--check') {
  writeFileSync(join(root, 'css/tokens.css'), css.join('\n'));
  mkdirSync(join(root, 'src/generated'), { recursive: true });
  writeFileSync(join(root, 'src/generated/tokens.ts'), ts);
  console.log('\nwrote css/tokens.css and src/generated/tokens.ts');
}
